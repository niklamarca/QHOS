def by_id(fid: str) -> FabConcept:
    for row in CONCEPTS:
        if row.id == fid:
            return row
    raise KeyError(fid)


def classification_counts() -> Dict[str, int]:
    out = {k: 0 for k in CLASSIFICATIONS}
    for row in CONCEPTS:
        out[row.classification] = out.get(row.classification, 0) + 1
    return out


def completeness_report() -> Dict[str, Any]:
    missing_class = [r.id for r in CONCEPTS if r.classification not in CLASSIFICATIONS]
    missing_map = [r.id for r in CONCEPTS if not r.brain]
    missing_impl = [
        r.id for r in CONCEPTS
        if r.classification in {"ADOPT", "ADAPT"} and r.status not in {"IMPLEMENTED", "DEFERRED"}
    ]
    missing_reason = [
        r.id for r in CONCEPTS
        if r.classification.startswith("REJECT") and r.status != "REJECTED"
    ]
    deferred = [r.id for r in CONCEPTS if r.status == "DEFERRED"]
    return {
        "n": len(CONCEPTS),
        "counts": classification_counts(),
        "missing_classification": missing_class,
        "missing_mapping": missing_map,
        "adopt_adapt_without_impl_or_defer": missing_impl,
        "rejects_without_reason": missing_reason,
        "deferred": deferred,
        "complete": not (missing_class or missing_map or missing_impl or missing_reason),
    }


def render_matrix_markdown() -> str:
    lines = [
        "# Fable integration matrix",
        "",
        "Fable is a source of operating principles. It is not the Brain.",
        "Prompts are not transplanted. Sources are pinned. Auto-sync is forbidden.",
        "",
        f"Concepts: **{len(CONCEPTS)}**. Analysis: 2026-09-02.",
        "",
        "| ID | Concept | Source | Class | Brain | Implementation | Tests | Status |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for row in CONCEPTS:
        lines.append(
            f"| {row.id} | {row.name} | {row.source} | {row.classification} | "
            f"{row.brain} | {row.implementation} | {row.tests} | {row.status} |"
        )
    lines.extend(["", "## Deferred", ""])
    for row in CONCEPTS:
        if row.status == "DEFERRED":
            lines.append(f"- **{row.id} {row.name}**: {row.notes or 'deferred'}")
    lines.extend(["", "## Completeness", "", "See `completeness_report()` and `tests/test_brain_fable.py`.", ""])
    return "\n".join(lines)
